import type { RequestState } from "./agentTrace";
import { MediaType } from "./types";

export function failureInjectionEnabled(): boolean {
  return process.env.ENABLE_FAILURE_INJECTION === "true" && process.env.NODE_ENV !== "production";
}

export type ProviderFailureKind = "auth" | "rate_limit" | "timeout" | "server";

export interface TestInjection {
  providerFailure?: ProviderFailureKind;
  missingMedia?: MediaType[];
}

export function buildInjectedProviderError(kind: ProviderFailureKind): Error {
  const leak = "Incorrect API key provided: sk-TESTLEAK1234567890 at https://api.openai.com/v1/chat/completions";
  const error = new Error(leak) as Error & { statusCode?: number };
  if (kind === "auth") error.statusCode = 401;
  if (kind === "rate_limit") error.statusCode = 429;
  if (kind === "server") error.statusCode = 503;
  if (kind === "timeout") error.name = "TimeoutError";
  return error;
}

export function testRateLimitOverride(req: Request): number | undefined {
  if (!failureInjectionEnabled()) return undefined;
  const value = Number(req.headers.get("x-test-rate-limit"));
  return Number.isInteger(value) && value > 0 && value <= 100 ? value : undefined;
}

/**
 * The only seam between the agent and the failure-injection test hooks. The agent talks to
 * `AgentHooks` and never to `TestInjection`, so production code paths contain no test logic;
 * with no injection the hooks object is simply empty.
 */
export interface AgentHooks {
  /** Media types to report as missing from the server. */
  missingMedia?: MediaType[];
  /** Take the model path even when no API key is configured. */
  forceModelPath?: boolean;
  /** Runs just before the model request is made; may throw to simulate a provider failure. */
  beforeModelCall?: (state: RequestState) => void;
  /** Router-reason text for a failed model request, when the failure was simulated. */
  describeFailure?: (errorLabel: string) => string;
}

export function hooksFromInjection(injection: TestInjection = {}): AgentHooks {
  const kind = injection.providerFailure;
  const hooks: AgentHooks = { missingMedia: injection.missingMedia };
  if (!kind) return hooks;
  return {
    ...hooks,
    forceModelPath: true,
    beforeModelCall: (state) => {
      state.failureInjected = true;
      state.modelSkipReason = `Simulated provider failure (test hook, ${kind}): the error was generated locally, so no request was sent to the model provider.`;
      throw buildInjectedProviderError(kind);
    },
    describeFailure: (label) => `Simulated provider failure (${label}): generated by the test hook, no real provider request was made. Details are logged on the server only.`,
  };
}
